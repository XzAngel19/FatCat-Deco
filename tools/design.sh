#!/usr/bin/env bash
# One command for menu design work: build the layout, draw it, audit it.
#
#   bash tools/design.sh                 # Main tab, PNG + audit in build/
#   bash tools/design.sh --project       # the decompiler tabs instead
#   bash tools/design.sh --zoom 2        # 2x render for pixel review
#   bash tools/design.sh --strict        # warnings fail the run
#   bash tools/design.sh --no-audit      # just the PNG
#
# The layout dump comes from the same mocked-DataModel harness the test suite
# uses (tools/fatchub/layout.lua), so what you see here is what the specs
# exercise: if a row is cut in the PNG it is cut in the hub.
set -euo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")/.."

PROJECT=0
ZOOM=1
AUDIT=1
STRICT=""
NAME="FatCatHub"

while [ $# -gt 0 ]; do
    case "$1" in
        --project) PROJECT=1; NAME="FatCatHub-project" ;;
        --zoom) shift; ZOOM="${1:-1}" ;;
        --no-audit) AUDIT=0 ;;
        --strict) STRICT="--strict" ;;
        -h|--help) sed -n '2,12p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'; exit 0 ;;
        *) echo "design: unknown option $1" >&2; exit 2 ;;
    esac
    shift
done

LUAU="${LUAU:-tools/luau/bin/luau}"
if [ ! -x "$LUAU" ]; then
    bash tools/luau/setup.sh >/dev/null
fi

mkdir -p build

# --- 1. layout dump -------------------------------------------------------
# Note the `if`: `[ ... ] && echo` as a command substitution returns 1 when the
# test fails, and `set -e` turns that into a silent exit with no message.
suffix=""
if [ "$PROJECT" = 1 ]; then
    suffix=".project"
fi
out="build/layout$suffix.txt"
chunk="build/layout$suffix.lua"

{
    echo "-- GENERATED by tools/design.sh: metrics + mock + library + (project) + sample + layout"
    # Real glyph advances so the mock's TextBounds matches the PNG. If no font
    # is found the mock falls back to its own estimate and the run still works.
    python3 tools/fatchub/metrics.py || echo "-- no font metrics available; mock fallback"
    echo
    cat tools/fatchub/mock.lua
    echo
    cat src/FatCatHub.lua
    echo
    if [ "$PROJECT" = 1 ]; then
        cat src/FatCatHub.project.lua
        echo
        echo 'Hub:SelectTab("Decompiler")'
        echo
    fi
    cat tools/fatchub/sample.lua
    echo
    cat tools/fatchub/layout.lua
} >"$chunk"

tools/luau/bin/luau-compile "$chunk" >/dev/null
"$LUAU" "$chunk" >"$out" 2>build/layout.err || {
    echo "design: the layout pass failed" >&2
    cat build/layout.err >&2
    exit 1
}

# --- 2. render ------------------------------------------------------------
png="build/$NAME.png"
python3 tools/fatchub/render.py "$out" "$png" --zoom "$ZOOM"

# --- 3. audit -------------------------------------------------------------
if [ "$AUDIT" = 1 ]; then
    echo
    python3 tools/fatchub/audit.py "$out" --json "build/$NAME.audit.json" $STRICT
fi

echo
echo "design: $png"
echo "design: build/$NAME.audit.json"
