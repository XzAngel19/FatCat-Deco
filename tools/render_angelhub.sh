#!/usr/bin/env bash
# Render the built shell to a PNG so it can be inspected without Roblox.
#
#   bash tools/render_angelhub.sh            # -> build/AngelHub.png
#
# Mock + hub + sample rows + layout dump, then tools/angelhub/render.py draws
# the reported rects. Text is drawn as a placeholder bar (no font metrics), so
# the image proves geometry, stacking, colour and clipping, not letterforms.
set -euo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")/.."

LUAU="${LUAU:-tools/luau/bin/luau}"
if [ ! -x "$LUAU" ]; then
    bash tools/luau/setup.sh >/dev/null
fi

mkdir -p build
out=build/render_angelhub.lua

{
    echo "-- GENERATED by tools/render_angelhub.sh"
    cat tools/angelhub/mock.lua
    echo
    cat src/AngelHub.lua
    echo
    cat tools/angelhub/sample.lua
    echo
    cat tools/angelhub/layout.lua
} > "$out"

tools/luau/bin/luau-compile "$out"
"$LUAU" "$out" > build/layout.txt 2>build/layout.err || {
    cat build/layout.err
    exit 1
}
python3 tools/angelhub/render.py build/layout.txt "${1:-build/AngelHub.png}"
