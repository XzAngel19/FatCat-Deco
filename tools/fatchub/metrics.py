#!/usr/bin/env python3
"""Pack real font advances into a small Luau module for the mock.

Why this exists: components size themselves from `TextBounds`, which is a
Roblox-computed property. The mock has to answer it, and the answer has to
match what the PNG shows or the specs and the screenshot disagree.

`tools/design.sh` runs this before the layout pass and emits a Luau table of
advances (fraction-of-em) for the printable ASCII range. The mock reads it via
`_G.TextMetrics`. Keyed by character, so the Luau side is a plain lookup.

    python3 tools/fatchub/metrics.py > build/textmetrics.lua
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import font as fontmod  # noqa: E402


def pack(family: str = "Gotham") -> str:
    face = fontmod.load(family)
    if face is None:
        raise SystemExit("metrics: no usable font found on this machine")

    entries = []
    for code in range(32, 127):
        char = chr(code)
        advance = face.advance(char) / face.upem
        # Lua source: key by the character itself, quoted for ' and \.
        key = char.replace("\\", "\\\\").replace("'", "\\'")
        entries.append(f"\t['{key}'] = {advance:.6f},")

    return (
        "-- GENERATED by tools/fatchub/metrics.py -- do not edit.\n"
        f"-- Advances from {face.path.name}, unitsPerEm {face.upem}.\n"
        "_G.TextMetrics = {\n"
        "\tfamily = '" + family + "',\n"
        f"\tlineHeight = {(face.ascent - face.descent):.6f},\n"
        "\tadvance = {\n" + "\n".join(entries) + "\n\t},\n"
        "}\n"
    )


if __name__ == "__main__":
    sys.stdout.write(pack())
