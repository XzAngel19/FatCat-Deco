#!/usr/bin/env bash
# Build and run the FatCat Hub harness.
#
#   bash tools/test_fatchub.sh
#
# Concatenates, in order: the Roblox mock, src/FatCatHub.lua and the assertions.
# The result is one chunk (build/test_fatchub.lua) run by the real Luau VM.
# Inlining instead of loadstring() is deliberate: the wasm VM cannot re-enter
# its compiler from a JS callback, and the original FatCat Hub shipped the same
# shape (one script, shell block then feature block).
set -euo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")/.."

LUAU="${LUAU:-tools/luau/bin/luau}"
if [ ! -x "$LUAU" ]; then
    bash tools/luau/setup.sh >/dev/null
fi

mkdir -p build
out=build/test_fatchub.lua

{
    echo "-- GENERATED by tools/test_fatchub.sh: mock + src/FatCatHub.lua + spec."
    cat tools/fatchub/mock.lua
    echo
    echo "-- ======== src/FatCatHub.lua ========"
    cat src/FatCatHub.lua
    echo
    cat tools/fatchub/spec.lua
} > "$out"

"${LUAU_COMPILE:-tools/luau/bin/luau-compile}" "$out"
"$LUAU" "$out"

# The project file is a second script, run against a fresh hub: the first spec
# destroys the window on purpose, so the two cannot share a process.
out=build/test_fatchub_project.lua
{
    echo "-- GENERATED by tools/test_fatchub.sh: mock + library + project file + spec."
    cat tools/fatchub/mock.lua
    echo
    echo "-- ======== src/FatCatHub.lua ========"
    cat src/FatCatHub.lua
    echo
    echo "-- ======== src/FatCatHub.project.lua ========"
    cat src/FatCatHub.project.lua
    echo
    cat tools/fatchub/project_spec.lua
} > "$out"

"${LUAU_COMPILE:-tools/luau/bin/luau-compile}" "$out" >/dev/null
"$LUAU" "$out"
