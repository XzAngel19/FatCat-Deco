#!/usr/bin/env bash
# Build and run the Fat Cat Project bundle harness.
#
#   bash tools/test_fatchub_bundle.sh
#
# Concatenates, in order: the Roblox mock, the generated bundle, the
# assertions. The result is one chunk (build/test_fatchub_bundle.lua) run by
# the real Luau VM against a simulated DataModel.
#
# Why the bundle and not each module: the bundle is what an executor actually
# downloads, and the bugs this catches (a module body touching an undefined
# symbol, a factory called without its Core, a module missing from the build)
# only exist in the assembled file. The per-module analyzer runs separately in
# tools/validate.sh.
#
# Wrapping the bundle in a function is required, exactly as in the loader
# harness: the bundle ends with `return Init, Booted`, and a top-level return
# would end the chunk before the assertions ran.
set -euo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")/.."

LUAU="${LUAU:-tools/luau/bin/luau}"
if [ ! -x "$LUAU" ]; then
    bash tools/luau/setup.sh >/dev/null
fi

python3 tools/build_bundle.py --check >/dev/null || {
    echo "the bundle is stale; rebuilding"
    python3 tools/build_bundle.py >/dev/null
}

# The tree the user asked for: five folders, literal names, `&` and spaces
# included. Checked here because this is the gate that runs on the assembled
# project, and because a rename would otherwise only show up as a diff nobody
# reads. The bundle does not care (it searches by module name), so nothing else
# would fail.
python3 - <<'CHECK'
import sys
from pathlib import Path

EXPECTED = {
    "Core & Initialization": {"FatCatSignal", "FatCatCore", "FatCatEnv", "FatCatConfig", "FatCatInit"},
    "UI & Styling Engine": {"FatCatDesign", "FatCatMaterials", "FatCatMenu"},
    "Creation & Inspection Tools": {"FatCatCreate", "FatCatInspect"},
    "Advanced Analysis, Exploitation & Anti-Tamper": {
        "FatCatExtractor", "FatCatDecompiler", "FatCatStealer", "FatCatSpy",
        "FatCatProjectiles", "FatCatVMHook", "FatCatMemoryScanner", "FatCatEnvSpoofer",
    },
    "Utilities, Console & Math": {"FatCatMath", "FatCatUniversal", "FatCatConsole"},
}

root = Path("src/project")
problems = []
if not root.is_dir():
    problems.append("src/project/ is missing")
else:
    on_disk = {path.name for path in root.iterdir() if path.is_dir()}
    for folder in EXPECTED:
        if folder not in on_disk:
            problems.append(f"missing folder: {folder!r}")
            continue
        actual = {path.stem for path in (root / folder).glob("*.lua")}
        for name in sorted(EXPECTED[folder] - actual):
            problems.append(f"{name}.lua is not in {folder!r}")
        for name in sorted(actual - EXPECTED[folder]):
            problems.append(f"{name}.lua does not belong in {folder!r}")
    # No stray modules at the flat level: the folders are the structure now.
    loose = sorted(path.name for path in root.glob("*.lua"))
    if loose:
        problems.append("loose modules at src/project/: " + ", ".join(loose))

if problems:
    for problem in problems:
        print("FAIL structure: " + problem)
    sys.exit(1)
print("PASS the five folders are where they should be")
CHECK

mkdir -p build
out=build/test_fatchub_bundle.lua

{
    echo "-- GENERATED by tools/test_fatchub_bundle.sh: mock + bundle + spec."
    cat tools/fatchub/mock.lua
    echo
    echo "-- ======== src/FatCatHub.bundle.lua, wrapped so its final return stays local ========"
    echo "local function runBundle()"
    echo "return function()"
    cat src/FatCatHub.bundle.lua
    echo "end"
    echo "end"
    echo
    echo "local Init, Booted = (runBundle())()"
    echo
    cat tools/fatchub/bundle_spec.lua
} > "$out"

"${LUAU_COMPILE:-tools/luau/bin/luau-compile}" "$out" >/dev/null
"$LUAU" "$out"

# ---------------------------------------------------------------------------
# Degraded boot
#
# The requirement is that one broken module does not cost the user the menu.
# That cannot be asserted in the main chunk: the bundle has already booted
# there and Core is destroyed by the spec's teardown. So the same bundle gets
# a second, isolated run with one optional module poisoned on the way in.
# ---------------------------------------------------------------------------
degraded=build/test_fatchub_bundle_degraded.lua
{
    echo "-- GENERATED by tools/test_fatchub_bundle.sh: degraded boot."
    cat tools/fatchub/mock.lua
    echo
    echo "local function runBundle()"
    echo "return function()"
    # The factory table is built inside the bundle, so the poison has to be
    # injected by wrapping the module source instead.
    python3 - <<'PYGEN'
import pathlib, re
body = pathlib.Path("src/FatCatHub.bundle.lua").read_text()
# Break the Materials module at build time: its factory throws.
marker = "Modules['FatCatMaterials'] = module"
assert marker in body, "the Materials assignment moved; update the degraded test"
body = body.replace(
    marker,
    "Modules['FatCatMaterials'] = function() error('spec: Materials is broken', 0) end",
    1,
)
# `body` already ends with the bundle's own closing `return`, so it goes in
# verbatim between runBundle()'s two `end`s, which the shell echoes below.
print(body)
print("end")
print("end")
PYGEN
    echo
    echo "local Ok, Result = pcall((runBundle()))"
    cat tools/fatchub/degraded_spec.lua
} > "$degraded"

"${LUAU_COMPILE:-tools/luau/bin/luau-compile}" "$degraded" >/dev/null
"$LUAU" "$degraded"
