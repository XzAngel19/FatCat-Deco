#!/usr/bin/env bash
# Build and run the Angel Hub harness.
#
#   bash tools/test_angelhub.sh
#
# Concatenates, in order: the Roblox mock, src/AngelHub.lua, the assertions.
# The result is one chunk (build/test_angelhub.lua) run by the real Luau VM.
# Inlining instead of loadstring() is deliberate: the wasm VM cannot re-enter
# its compiler from a JS callback, and the original Angel Hub shipped the same
# shape (one script, shell block then feature block).
set -euo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")/.."

LUAU="${LUAU:-tools/luau/bin/luau}"
if [ ! -x "$LUAU" ]; then
    bash tools/luau/setup.sh >/dev/null
fi

mkdir -p build
out=build/test_angelhub.lua

{
    echo "-- GENERATED by tools/test_angelhub.sh: mock + src/AngelHub.lua + spec."
    cat tools/angelhub/mock.lua
    echo
    echo "-- ======== src/AngelHub.lua ========"
    cat src/AngelHub.lua
    echo
    cat tools/angelhub/spec.lua
} > "$out"

"${LUAU_COMPILE:-tools/luau/bin/luau-compile}" "$out"
"$LUAU" "$out"
