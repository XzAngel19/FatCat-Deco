#!/usr/bin/env bash
# Build and run the FatCat Hub loader harness.
#
#   bash tools/test_fatchub_loader.sh
#
# The loader is download-and-compile glue, so it is tested with no network: the
# executor surface (game:HttpGet, loadstring, getgenv, print, warn) is mocked and
# the loader is inlined into the chunk. Inlining is required because this VM
# deadlocks when a chunk calls loadstring on another chunk.
#
# Covers: an HTML error page, a truncated body, a file that is not the library,
# a syntax error inside the library, HttpGet throwing, and the happy path.
set -euo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")/.."

LUAU="${LUAU:-tools/luau/bin/luau}"
if [ ! -x "$LUAU" ]; then
    bash tools/luau/setup.sh >/dev/null
fi

mkdir -p build
out=build/test_fatchub_loader.lua

{
    echo "-- GENERATED by tools/test_fatchub_loader.sh: mock + loader + spec."
    cat tools/fatchub/loader_mock.lua
    echo
    echo "-- ======== src/FatCatHub.loader.lua, wrapped so its early returns stay local ========"
    # The loader returns early on every failure path, and a top-level return
    # would end this generated chunk before the assertions ran. Wrapping it in
    # a function keeps the loader byte-for-byte as shipped.
    echo "local function runLoader()"
    cat src/FatCatHub.loader.lua
    echo
    echo "end"
    echo
    cat tools/fatchub/loader_spec.lua
} > "$out"

"${LUAU_COMPILE:-tools/luau/bin/luau-compile}" "$out" >/dev/null
"$LUAU" "$out"
