#!/usr/bin/env python3
"""Build the Fat Cat Project single-file bundle.

The project ships as twenty source files under src/project/, but an executor can
only fetch one URL and run one string. This script concatenates them into a
single Luau chunk:

    src/FatCatHub.bundle.lua     -- the project, ready to run
    build/FatCatHub.bundle.lua   -- same file, for the design harness

Layout of the generated chunk:

    header comment + the module table
    do ... end                   one block per module, each storing its value
    local Modules = { ... }      dispatch table by name
    local Init = <FatCatInit>    (the bootstrapper, verbatim)
    return Init(Modules)         boot, and hand back the Init table

Why a do-block per module: `local` at the top level of a chunk is shared by the
whole chunk, so twenty modules named `local Core` would collide. Each block has
its own scope, and the only values that escape are the ones stored in `Modules`.

Why the loader lives in a separate file: src/FatCatHub.loader.lua has to stay
tiny and self-contained (it is what the user runs first), so the bundle is what
*it* downloads, not the other way round.

Usage:
    python3 tools/build_bundle.py            # write src/ + build/
    python3 tools/build_bundle.py --check    # fail if src/ is stale
"""

from __future__ import annotations

import argparse
import hashlib
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PROJECT = ROOT / "src" / "project"
# The five folders are the structure the user asked for, with the literal `&`
# and spaces. They are on disk now, so every lookup below is a recursive search
# rather than a path guess: one module name can only match one file.
INIT_NAME = "FatCatInit"
# The window shell is not part of the user's module tree: it lives at src/ and
# is the code the 94 harness asserts and the design renders measure. The bundle
# carries it as a module so the loader still downloads one file.
SHELL = ROOT / "src" / "FatCatHub.lua"
OUTPUT = ROOT / "src" / "FatCatHub.bundle.lua"
BUILD_OUTPUT = ROOT / "build" / "FatCatHub.bundle.lua"

# Load order is the *load* order, not the folder order: signals first, then the
# core, then the modules that need a core to exist. FatCatInit also enforces
# this at runtime; the list here is what keeps the generated file readable.
MODULES = [
    "FatCatSignal",
    "FatCatCore",
    "FatCatEnv",
    "FatCatConfig",
    "FatCatDesign",
    "FatCatMaterials",
    "FatCatMath",
    "FatCatInspect",
    "FatCatCreate",
    "FatCatExtractor",
    "FatCatDecompiler",
    "FatCatStealer",
    "FatCatSpy",
    "FatCatProjectiles",
    "FatCatVMHook",
    "FatCatMemoryScanner",
    "FatCatEnvSpoofer",
    "FatCatUniversal",
    "FatCatConsole",
    "FatCatMenu",
]

# name -> path, for modules that do not live under src/project/. The window
# shell is the only one: it is the code the 94 harness asserts measure, and it
# is not part of the user's module tree.
EXTRA_MODULES = {
    "FatCatShell": SHELL,
}

HEADER = """\
-- Fat Cat Project {version} -- generated by tools/build_bundle.py, do not edit.
--
-- Sources: {count} modules under src/project/ plus the window shell.
-- Rebuild with: python3 tools/build_bundle.py
--
-- Every module below is a file from the repository, concatenated unchanged
-- inside its own do-block so its locals cannot collide with the next one. The
-- only values that escape are the ones stored in `Modules`, which FatCatInit
-- reads. If you are debugging a module, edit the file under its folder in
-- src/project/ and rebuild; editing this file is editing a build artifact.
-- The folder a module sits in is documentation, not dispatch: the bundle is
-- flat and every module is reached by bare name.
"""


ALL_MODULES = MODULES + list(EXTRA_MODULES)


def path_relative(name: str) -> str:
    """Repository-relative path of a module, for the generated file map."""
    extra = EXTRA_MODULES.get(name)
    if extra is not None:
        return str(extra.relative_to(ROOT))
    matches = sorted(PROJECT.rglob(f"{name}.lua"))
    if not matches:
        return name
    return str(matches[0].relative_to(ROOT))


def module_path(name: str) -> Path:
    """The one file that defines `name`, wherever its folder puts it."""
    extra = EXTRA_MODULES.get(name)
    if extra is not None:
        if not extra.exists():
            raise SystemExit(f"build_bundle: {extra.relative_to(ROOT)} is missing")
        return extra
    matches = sorted(PROJECT.rglob(f"{name}.lua"))
    if not matches:
        raise SystemExit(f"build_bundle: no module named {name}.lua under {PROJECT.relative_to(ROOT)}")
    if len(matches) > 1:
        listed = ", ".join(str(path.relative_to(ROOT)) for path in matches)
        raise SystemExit(f"build_bundle: {name}.lua is defined twice: {listed}")
    return matches[0]


def read_module(name: str) -> str:
    """Find one module file: the extras table first, then the project tree."""
    return module_path(name).read_text(encoding="utf-8")


def indent(text: str, prefix: str = "\t") -> str:
    return "\n".join(prefix + line if line.strip() else line for line in text.splitlines())


def build() -> str:
    init_source = read_module(INIT_NAME)
    parts: list[str] = []

    total_bytes = 0
    for name in ALL_MODULES:
        source = read_module(name)
        total_bytes += len(source.encode("utf-8"))
        # The shell runs *last*, when FatCatInit asks for it, not when this
        # file is parsed. Two reasons:
        #   * its chunk ends with `if not defer then Hub.Init() end`, and the
        #     defer flag has to be raised before that line executes;
        #   * FatCatInit builds the menu against a Hub that must not have a
        #     window yet, or the default "Main" tab is built and then replaced.
        # So the block stores a factory the bootstrapper calls, and the file is
        # kept byte-for-byte inside it.
        if name == "FatCatShell":
            parts.append(
                f"-- ---------------------------------------------------------------------\n"
                f"-- {name}.lua -- run on demand by FatCatInit, not at load time.\n"
                f"-- ---------------------------------------------------------------------\n"
                f"do\n"
                f"\tlocal loadedShell = false\n"
                f"\tModules[{name!r}] = function()\n"
                f"\t\tif loadedShell then\n"
                f"\t\t\treturn true\n"
                f"\t\tend\n"
                f"\t\tloadedShell = true\n"
                f"{indent(source, chr(9) + chr(9))}\n"
                f"\t\treturn true\n"
                f"\tend\n"
                f"end\n"
            )
            continue

        folder = module_path(name).parent.name
        parts.append(
            f"-- ---------------------------------------------------------------------\n"
            f"-- {name}.lua  [{folder}]\n"
            f"-- ---------------------------------------------------------------------\n"
            f"do\n"
            f"\tlocal module = (function()\n"
            f"{indent(source, chr(9) + chr(9))}\n"
            f"\tend)()\n"
            f"\tModules[{name!r}] = module\n"
            f"end\n"
        )

    dispatch = ",\n".join(f"\t[{name!r}] = true" for name in ALL_MODULES)
    filesystem = ",\n".join(
        f"\t[{name!r}] = {str(path_relative(name))!r}" for name in ALL_MODULES
    )

    body = (
        HEADER.format(version="2.1.0", count=len(ALL_MODULES))
        + "\nlocal Modules = {}\n\n"
        + "".join(parts)
        + "\n-- ---------------------------------------------------------------------\n"
        + "-- FatCatInit.lua -- the bootstrapper.\n"
        + "-- ---------------------------------------------------------------------\n"
        + "-- FatCatInit is a factory: it takes the module table and returns the\n"
        + "-- bootstrapper. Calling it with Modules is what makes the two halves\n"
        + "-- independent: the same file works from this bundle and from a\n"
        + "-- checkout that loads each module by hand.\n"
        + "local InitFactory = (function()\n"
        + indent(init_source, "\t")
        + "\nend)()\n"
        + "local Init = InitFactory(Modules)\n\n"
        + "-- Which modules this build actually contains. A loader that fetches a\n"
        + "-- subset can still give FatCatInit a smaller table and get a clear\n"
        + "-- 'no module named X' instead of a nil call.\n"
        + "local Available = {\n"
        + dispatch
        + "\n}\n\n"
        + "do -- refuse to run with a hole in the build\n"
        + "\tfor name in Available do\n"
        + "\t\tif Modules[name] == nil then\n"
        + "\t\t\tprint(('[Fat Cat] the bundle is missing %s; rebuild with tools/build_bundle.py'):format(name))\n"
        + "\t\tend\n"
        + "\tend\n"
        + "end\n\n"
        + "-- Which file each module came from, for bug reports and for the\n"
        + "-- 'where is this defined' question. Not read at runtime.\n"
        + "Init.files = {\n"
        + filesystem
        + "\n}\n\n"
        + "-- Boot. Returning as a value (`return Init, Booted`) instead of running\n"
        + "-- the boot at the call site is what lets this file also be\n"
        + "-- concatenated into a test harness: a top-level `return` would end the\n"
        + "-- chunk and the assertions after it would never run. `pcall` because\n"
        + "-- Init.safeBoot never throws, but a broken DataModel must not take the\n"
        + "-- executor down with it either.\n"
        + "local Booted = Init.safeBoot()\n"
        + "Init.booted = Booted\n"
        + "return Init, Booted\n"
    )
    return body


def main() -> int:
    parser = argparse.ArgumentParser(description="Build the Fat Cat Project bundle.")
    parser.add_argument("--check", action="store_true", help="verify src/ is up to date instead of writing")
    args = parser.parse_args()

    bundle = build()
    digest = hashlib.sha256(bundle.encode("utf-8")).hexdigest()[:12]

    if args.check:
        if not OUTPUT.exists():
            print(f"FAIL {OUTPUT.relative_to(ROOT)} is missing; run tools/build_bundle.py")
            return 1
        current = OUTPUT.read_text(encoding="utf-8")
        if current != bundle:
            print(f"FAIL {OUTPUT.relative_to(ROOT)} is stale; run tools/build_bundle.py")
            return 1
        print(f"PASS bundle matches its sources ({len(bundle) // 1024} KiB, sha {digest})")
        return 0

    OUTPUT.write_text(bundle, encoding="utf-8")
    BUILD_OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    BUILD_OUTPUT.write_text(bundle, encoding="utf-8")

    lines = bundle.count("\n") + 1
    print(f"PASS wrote {OUTPUT.relative_to(ROOT)} ({lines} lines, {len(bundle) // 1024} KiB, sha {digest})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
